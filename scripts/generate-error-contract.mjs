#!/usr/bin/env node
// generate-error-contract.mjs —— 从主仓 error-catalog.md 生成 FE 契约值域（M4/M7 脚手架）。
//
// 思路对齐 #1126 recount：**机器可复算**取代人肉对账——
//   源 = fmby-v2 `docs/plans/v2-dev/contracts/error-catalog.md`（本表由代码派生，
//        真源 = error_code.rs as_slug/http_status，一致性由主仓单测锁定）；
//   出 = `shared/src/errors/error-catalog.generated.ts`：
//        · ERROR_CATALOG_SLUGS（全量 SCREAMING 值域——FE ApiError.code 的合法域）
//        · CODES_HTTP_429（Coded-429 码——#1838/M1 限额门白名单的单源）
//   ⇒ catalog 长码 FE/契约自动跟随，消除「wire 大小写/集合漂移」整类缺陷
//     （实证：error.ts 的 5 条 snake_case 死条目 = 手写集合与 wire 大小写漂移）。
//
// 用法：
//   node scripts/generate-error-contract.mjs --catalog <error-catalog.md> [--check] [--out <ts 路径>]
//     --check  比较生成的 TS 与磁盘现状，不一致 ⇒ rc=1（CI 门模式）
// 退出码：0 = 一致/已写出；1 = --check 不一致；2 = 判据不可用（catalog 缺失/解析失败）
//
// ★脚手架边界（TODO，另卡裁决）：
//   T1 retryable 派生规则（429+5xx+Retryable* 家族如何映射 FE retryable）待产品裁定；
//   T2 SCREAMING→snake 死条目清理与 #1871 夹具对齐联动（改 = 行为变更）；
//   T3 主仓路径发现（兄弟仓约定路径 / env FMBY_V2_ROOT / CI 注入）待编排侧定。

import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const args = process.argv.slice(2);
const get = (flag) => { const i = args.indexOf(flag); return i >= 0 ? args[i + 1] : undefined; };
const has = (flag) => args.includes(flag);
const catalogPath = get('--catalog');
const outPath = get('--out') || 'shared/src/errors/error-catalog.generated.ts';
const checkMode = has('--check');

if (!catalogPath || !existsSync(catalogPath)) {
  console.error(`[ENV] --catalog 缺失或文件不存在: ${catalogPath ?? '(未给)'}`);
  process.exit(2);
}

const src = readFileSync(catalogPath, 'utf8');
// 行格式：| `CODE` | <status> | <message> | <触发条件> | <运维建议> |
const ROW = /^\|\s*`([A-Z][A-Z0-9_]+)`\s*\|\s*(\d{3})\s*\|/;
const rows = [];
for (const line of src.split('\n')) {
  const m = ROW.exec(line);
  if (m) rows.push({ code: m[1], status: Number(m[2]) });
}

if (rows.length === 0) {
  console.error('[FAIL] error-catalog.md 解析出 0 行——表格式漂移，判据不可用');
  process.exit(2);
}

const codes429 = rows.filter((r) => r.status === 429).map((r) => r.code);
const all = rows.map((r) => r.code);

const ts = `// GENERATED by scripts/generate-error-contract.mjs —— 请勿手改（源 = fmby-v2 error-catalog.md）。
// 确定性输出（无时间戳）：--check 以字节比对；时间信息看 git。
// 行数：${rows.length}；429 码：${codes429.length}。
// 值域大小写照 wire 真值（error_code/slug.rs as_slug = SCREAMING_SNAKE）。

/** 主仓错误码目录全量值域（FE ApiError.code 的后端合法域）。 */
export const ERROR_CATALOG_SLUGS: ReadonlySet<string> = new Set([
${all.map((c) => `  '${c}',`).join('\n')}
]);

/** Coded-429 码（限流语义 ⇒ 一律可重试；#1838/M1 限额门白名单单源）。 */
export const CODES_HTTP_429: ReadonlySet<string> = new Set([
${codes429.map((c) => `  '${c}',`).join('\n')}
]);
`;

if (checkMode) {
  const disk = existsSync(outPath) ? readFileSync(outPath, 'utf8') : '';
  const ok = disk === ts;
  console.log(ok ? `✅ --check 一致（${rows.length} 码）` : `✗ --check 不一致（磁盘 ${disk.split('\n').length} 行 vs 生成 ${ts.split('\n').length} 行）`);
  process.exit(ok ? 0 : 1);
}

writeFileSync(outPath, ts);
console.log(`✅ 写出 ${outPath}（${rows.length} 码 / 429 × ${codes429.length}）`);
